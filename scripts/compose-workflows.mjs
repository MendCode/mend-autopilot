#!/usr/bin/env node
// Writes core/workflows/mend.js: mend-lite, then mend-lite-pr, then the pull request, as one run, so one
// approval takes a request all the way to an open pull request. Workflow scripts cannot import each other,
// so the two scripts are copied in as functions; edit mend-lite.js and mend-lite-pr.js, never mend.js.
// usage: node scripts/compose-workflows.mjs [--check]   (--check compares instead of writing; exit 1 on drift)

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIR = path.join(ROOT, 'core', 'workflows');
const TARGET = path.join(DIR, 'mend.js');

/** The script without its `export const meta = { ... }` block, which only the top level may declare. */
export function bodyOf(source, name) {
  const start = source.indexOf('export const meta = {');
  const end = source.indexOf('\n}\n', start);
  if (start !== 0 || end < 0) throw new Error(`[COMPOSE]: ${name} must start with its meta block`);
  return source.slice(end + 3).trim();
}

const indent = (text) => text.split('\n').map((line) => (line ? '  ' + line : line)).join('\n');

export function compose({ lite, litePr }) {
  return `export const meta = {
  name: "mend",
  description: "One item to one pull request: the strong model specs and reviews, a cheap owner implements, programs and an auditor prove it, then the branch is pushed and the pull request opened with its evidence card",
  phases: [
    { title: "Plan", detail: "worktree and planner spec" },
    { title: "Build", detail: "owner implements; workflow runs verification, scope and integrity" },
    { title: "Review", detail: "strong reviewer; a blocker sends one fix round" },
    { title: "Checks", detail: "checks, integrity, red-green at the reviewed head" },
    { title: "Audit", detail: "read-only auditor, not the owner or reviewer" },
    { title: "Card", detail: "light-path evidence card, schema-checked" },
    { title: "Publish", detail: "push the item branch, open or update its pull request; never merge" },
  ],
  // The host pauses a run once its agent count reaches the cap, even at the last call: leave headroom.
  budget: { agents: 12, minutes: 240 },
  permission: "edits",
  maxConcurrent: 1,
}

// GENERATED by scripts/compose-workflows.mjs from mend-lite.js and mend-lite-pr.js. Edit those two.
// Arguments: those of mend-lite (repo, item, pkg, critic, planner, model, fixRounds, engine) and of
// mend-lite-pr (auditor), plus publish: "no" keeps the branch local. A merge-ready item opens a ready
// pull request, a draft one a draft pull request with its reason; a blocked item is never pushed.

async function mendLite(args) {
${indent(bodyOf(lite, 'mend-lite.js'))}
}

async function mendLitePr(args) {
${indent(bodyOf(litePr, 'mend-lite-pr.js'))}
}

const built = await mendLite(args)
const proven = built.state === "reviewed" ? await mendLitePr(args) : null
const result = proven ?? built

phase("Publish")
const quoteArg = (value) => "'" + String(value).split("'").join("'\\"'\\"'") + "'"
const repoDir = String(args.repo ?? "").trim()
const pkgArg = String(args.pkg ?? "").trim()
const pkgDir = pkgArg.startsWith("/") ? pkgArg : repoDir + "/" + pkgArg
const itemArg = String(args.item ?? "").trim()
const itemFile = itemArg.startsWith("/") ? itemArg : repoDir + "/" + itemArg
if (String(args.publish ?? "yes").trim() === "no") return Object.assign({}, result, { published: false, publishReason: "publish=no" })
if (!["merge-ready", "draft"].includes(result.state) || !result.worktree || !result.branch) return Object.assign({}, result, { published: false, publishReason: "the item is " + result.state + "; nothing to publish" })
const card = proven?.card ?? { item: built.branch.slice("mend/".length), state: "draft", headSha: built.head, baseSha: built.baseSha }
const request = { worktree: result.worktree, branch: result.branch, card, item: itemFile, reason: result.state === "draft" ? result.reason : "" }
const published = await check("node " + quoteArg(pkgDir + "/checks/publish-pr.mjs") + " --stdin", { stdin: JSON.stringify({ args: [JSON.stringify(request)], policy: null }) })
const lines = String(published.detail ?? "").trim().split("\\n")
let outcome = null
for (const line of lines.reverse()) { if (line.trim().startsWith("{")) { try { outcome = JSON.parse(line.trim()) } catch {} break } }
if (!outcome) outcome = { published: false, reason: "publish-pr did not report: " + lines.reverse().join("\\n").slice(-300) }
log("publish", outcome.published ? outcome.url : outcome.reason)
return Object.assign({}, result, { published: outcome.published, pullRequest: outcome.url ?? null, publishReason: outcome.reason })
`;
}

const [lite, litePr] = await Promise.all(['mend-lite.js', 'mend-lite-pr.js'].map((name) => fs.readFile(path.join(DIR, name), 'utf8')));
const output = compose({ lite, litePr });
if (process.argv.includes('--check')) {
  const current = await fs.readFile(TARGET, 'utf8').catch(() => null);
  if (current !== output) {
    console.error('compose-workflows: core/workflows/mend.js differs from mend-lite.js and mend-lite-pr.js; run node scripts/compose-workflows.mjs');
    process.exit(1);
  }
} else {
  await fs.writeFile(TARGET, output);
}
